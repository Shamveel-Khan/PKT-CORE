def test_cli_info(capsys: pytest.CaptureFixture[str]) -> None:
    assert main(["info", str(LAB)]) == 0
    out = capsys.readouterr().out
    assert "root tag    : PACKETTRACER5" in out
    assert "cipher      : twofish" in out
    assert "network lab" in out


def test_cli_info_json(capsys: pytest.CaptureFixture[str]) -> None:
    assert main(["info", str(ACTIVITY), "--json"]) == 0
    out = capsys.readouterr().out
    payload = json.loads(out[out.index("{"):])
    assert payload["root_tag"] == "PACKETTRACER5_ACTIVITY"
    assert payload["is_activity"] is True


def test_cli_unpack_and_pack_roundtrip(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    out_dir = tmp_path / "unpacked"
    assert main(["unpack", str(LAB), "-o", str(out_dir)]) == 0
    xml_files = list(out_dir.glob("*.xml"))
    assert len(xml_files) == 1
    meta = json.loads((out_dir / (xml_files[0].stem + ".container.json")).read_text())
    assert meta["root_tag"] == "PACKETTRACER5"

    rebuilt = tmp_path / "rebuilt.pkt"
    assert main(["pack", str(xml_files[0]), "-o", str(rebuilt), "--verify", "--force"]) == 0
    assert "round-trip: OK" in capsys.readouterr().out

    # And the rebuilt container must hold byte-identical XML.
    assert decode(rebuilt).xml == decode(LAB).xml


def test_cli_pack_refuses_to_overwrite_without_force(tmp_path: Path) -> None:
    xml = tmp_path / "x.xml"
    xml.write_bytes(decode(LAB).xml)
    out = tmp_path / "out.pkt"
    out.write_bytes(b"precious")
    assert main(["pack", str(xml), "-o", str(out)]) == 1
    assert out.read_bytes() == b"precious"
    assert main(["pack", str(xml), "-o", str(out), "--force"]) == 0


def test_cli_diff_identical_is_exit_zero(capsys: pytest.CaptureFixture[str]) -> None:
    assert main(["diff", str(LAB), str(LAB)]) == 0
    assert "identical" in capsys.readouterr().out.lower()


def test_cli_diff_detects_differences(capsys: pytest.CaptureFixture[str]) -> None:
    assert main(["diff", str(LAB), str(ACTIVITY)]) == 1
    out = capsys.readouterr().out
    assert "root tag" in out
    assert "*" in out


def test_cli_diff_unified(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    """A one-character XML edit should surface as a unified diff."""
    xml = decode(LAB).xml
    variant = tmp_path / "variant.pkt"
    encode_bytes_out = encode_bytes(xml.replace(b"9.0.1.0858", b"9.0.1.0999", 1))
    variant.write_bytes(encode_bytes_out)

    assert main(["diff", str(LAB), str(variant), "--unified"]) == 1
    out = capsys.readouterr().out
    assert "9.0.1.0999" in out


def test_cli_error_on_missing_file(capsys: pytest.CaptureFixture[str]) -> None:
    assert main(["info", str(LAB.with_name("nope.pkt"))]) == 2
    assert "error:" in capsys.readouterr().err


def test_cli_error_on_non_container(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    junk = tmp_path / "junk.pkt"
    junk.write_bytes(bytes(range(256)) * 4)
    assert main(["info", str(junk)]) == 2
    assert "error:" in capsys.readouterr().err


