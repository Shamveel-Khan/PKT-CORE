"""End-to-end tests for the ``pkt`` CLI and the container codec.

These run against the two *committed* sample containers in ``corpus/samples/``,
so they work with no corpus download. Both are generated by this project's own
tooling and are GPL-3.0.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from pkt_core import (
    Container,
    IntegrityError,
    decode,
    decode_bytes,
    encode_bytes,
    root_tag,
)
from pkt_core.cli.main import main

REPO = Path(__file__).resolve().parent.parent
SAMPLES = REPO / "corpus" / "samples"
LAB = SAMPLES / "sample_lab.pkt"
ACTIVITY = SAMPLES / "sample_activity.pka"

pytestmark = pytest.mark.skipif(
    not (LAB.exists() and ACTIVITY.exists()),
    reason="committed sample containers are missing",
)


# --------------------------------------------------------------------------
# Container codec
# --------------------------------------------------------------------------
@pytest.mark.parametrize("path,expected_root", [(LAB, "PACKETTRACER5"), (ACTIVITY, "PACKETTRACER5_ACTIVITY")])
def test_samples_decode(path: Path, expected_root: str) -> None:
    container = decode(path)
    assert container.root_tag == expected_root
    assert container.format_name == "pkt"
    assert container.raw is not None


def test_activity_flag_is_derived_from_root_tag() -> None:
    assert decode(ACTIVITY).is_activity is True
    assert decode(LAB).is_activity is False


def test_xml_roundtrip_is_byte_exact() -> None:
    for path in (LAB, ACTIVITY):
        original = decode(path)
        rebuilt = encode_bytes(original.xml, original.format_name)
        again = decode_bytes(rebuilt)
        assert again.xml == original.xml
        assert again.root_tag == original.root_tag


def test_encode_is_deterministic() -> None:
    """Fixed key + fixed IV => identical XML must yield identical bytes."""
    xml = decode(LAB).xml
    assert encode_bytes(xml) == encode_bytes(xml)


def test_container_roundtrip_reproduces_file_bytes() -> None:
    """encode(decode(f)) == f — the strongest invariant the format offers."""
    for path in (LAB, ACTIVITY):
        original = path.read_bytes()
        container = decode_bytes(original)
        assert encode_bytes(container.xml, container.format_name) == original


def test_detect_format_uses_the_tag_not_a_prefix() -> None:
    from pkt_core.codec.container import detect_format

    for path in (LAB, ACTIVITY):
        assert detect_format(path.read_bytes()) == "pkt"


def test_corrupt_file_fails_detection() -> None:
    """A flipped byte means no format authenticates, so detection rejects it."""
    from pkt_core.errors import FormatError

    raw = bytearray(LAB.read_bytes())
    raw[0] ^= 0xFF
    with pytest.raises(FormatError):
        decode_bytes(bytes(raw))


def test_corrupt_tag_is_rejected_when_format_is_forced() -> None:
    """With the flavour pinned, the failure surfaces as an AEAD tag mismatch."""
    raw = bytearray(LAB.read_bytes())
    raw[0] ^= 0xFF
    with pytest.raises(IntegrityError):
        decode_bytes(bytes(raw), "pkt")


def test_corrupt_tag_can_still_be_inspected_explicitly() -> None:
    """Forensics escape hatch: the plaintext is returned even on tag failure."""
    raw = bytearray(LAB.read_bytes())
    raw[0] ^= 0xFF
    container = decode_bytes(bytes(raw), "pkt", verify_tag=False)
    assert isinstance(container, Container)


def test_truncated_input_raises_cleanly() -> None:
    from pkt_core.errors import TruncatedFileError

    with pytest.raises(TruncatedFileError):
        decode_bytes(b"\x00" * 8)


def test_root_tag_helper() -> None:
    assert root_tag(b"<PACKETTRACER5><X/></PACKETTRACER5>") == "PACKETTRACER5"
    assert root_tag(b"  <A b='1'>") == "A"
    assert root_tag(b"not xml at all") == "?"


